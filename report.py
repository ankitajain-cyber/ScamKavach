import hashlib
import html
from datetime import datetime, timezone, timedelta

IST = timezone(timedelta(hours=5, minutes=30))

CSS = """
body{font-family:'Noto Sans Devanagari','Nirmala UI',Arial,sans-serif;max-width:800px;margin:30px auto;padding:0 16px;color:#111;line-height:1.5}
h1{margin-bottom:0}h2{border-bottom:2px solid #ddd;padding-bottom:4px;margin-top:28px}
.box{background:#f5f5f5;padding:12px;border-radius:6px;white-space:pre-wrap;word-break:break-word}
.hash{font-family:monospace;word-break:break-all}
.verdict{font-size:20px;font-weight:bold}
.small{color:#555;font-size:13px}
.warn{background:#fff7e0;border-left:5px solid #e0a000;padding:8px 12px;margin:10px 0}
table.t td{padding:2px 12px 2px 0;vertical-align:top}
@media print{body{margin:0}}
"""


def _list(items, empty="None found"):
    if not items:
        return f"<p><i>{empty}</i></p>"
    body = "".join(f"<li>{html.escape(str(i))}</li>" for i in items)
    return f"<ul>{body}</ul>"


def _fmt(dt):
    utc = dt.astimezone(timezone.utc).strftime("%d %b %Y, %H:%M:%S")
    ist = dt.astimezone(IST).strftime("%d %b %Y, %H:%M:%S")
    return f"{utc} UTC &nbsp;/&nbsp; {ist} IST"


def build_report_html(message, result, rules, final_risk, level, indicators, analyzed_at=None):
    generated = datetime.now(timezone.utc)
    analyzed = analyzed_at or generated
    sha = hashlib.sha256(message.encode("utf-8")).hexdigest()
    report_id = "SKV-" + analyzed.strftime("%Y%m%d-%H%M%S") + "-" + sha[:6].upper()
    e = lambda s: html.escape(str(s))

    rule_lines = [f"{name} (found: {matched})" for name, matched in rules["hits"]]
    ind_html = "".join(
        f"<p><b>{e(k)}</b></p>{_list(v)}" for k, v in indicators.items()
    )
    fallback = bool(result.get("_fallback"))
    source = result.get("_source", "live AI")

    fallback_box = ""
    if fallback:
        fallback_box = (
            "<div class='warn'><b>AI was unavailable.</b> This assessment uses rule-based "
            "checks only and is less reliable than the full AI analysis.</div>"
        )
    mask_note = ""
    if source == "live AI":
        mask_note = (
            "<p class='small'>Before the AI analysis, phone numbers, Aadhaar-like numbers, card "
            "numbers, PAN numbers and OTP codes were masked. This report shows the original text.</p>"
        )

    body = f"""
<h1>ScamKavach Incident Report</h1>
<table class="t small">
<tr><td><b>Report ID</b></td><td>{e(report_id)}</td></tr>
<tr><td><b>Message analyzed at</b></td><td>{_fmt(analyzed)}</td></tr>
<tr><td><b>Report generated at</b></td><td>{_fmt(generated)}</td></tr>
<tr><td><b>Analysis source</b></td><td>{e(source)} | model: {e(result.get('_model'))}</td></tr>
</table>
<p class="small">Times come from the server clock of the ScamKavach app (UTC), shown with the IST equivalent.</p>

<h2>1. Message as submitted</h2>
<div class="box">{e(message)}</div>
<p><b>SHA-256:</b> <span class="hash">{sha}</span></p>
<p class="small">The hash covers the exact text entered into ScamKavach (UTF-8). It shows this text was not altered after submission. It does not prove the original message is authentic.</p>

<h2>2. Assessment</h2>
{fallback_box}
<p class="verdict">{e(result.get('label'))} | Risk {final_risk}/100 ({e(level)})</p>
<p>AI confidence: {"n/a" if fallback else e(result.get('confidence')) + "%"}</p>
<p><b>Why (English):</b> {e(result.get('explanation_en', ''))}</p>
<p><b>क्यों (हिन्दी):</b> {e(result.get('explanation_hi', ''))}</p>
<p><b>Advice (English):</b> {e(result.get('advice_en', ''))}</p>
<p><b>सलाह (हिन्दी):</b> {e(result.get('advice_hi', ''))}</p>
<p><b>Red flags:</b></p>{_list(result.get('red_flags', []))}
<p><b>Rule-based checks:</b></p>{_list(rule_lines)}
{mask_note}

<h2>3. Extracted indicators</h2>
{ind_html}

<h2>4. What to do now</h2>
<ul>
<li>Do not reply, click links, or share OTPs, PINs or card details.</li>
<li>Keep the original message and chat. Do not delete them. Take screenshots showing the sender and time.</li>
<li>If money was lost, call <b>1930</b> immediately and tell your bank.</li>
<li>Report at <b>cybercrime.gov.in</b> and attach this report with your screenshots.</li>
</ul>

<h2>5. Limitations</h2>
<p class="small">This report was generated by an AI-assisted tool and may contain errors. It is not legal advice and does not replace a police complaint or a certified forensic examination. Courts may require a Section 63(4) BSA certificate for electronic records.</p>
"""
    return (
        "<!DOCTYPE html><html><head><meta charset='utf-8'>"
        f"<title>{e(report_id)}</title><style>{CSS}</style></head><body>{body}</body></html>"
    )